import type { ComponentId, MachineFlag, Mission, MissionStep, VerifySpec } from '../types';

// ---------- مساعدات بناء خطوات التحقق (بدون any) ----------
const flagOn = (target: MachineFlag): VerifySpec => ({ kind: 'flag-on', target });
const flagOff = (target: MachineFlag): VerifySpec => ({ kind: 'flag-off', target });
const partRemoved = (target: ComponentId): VerifySpec => ({ kind: 'part-removed', target });
const partInstalled = (target: ComponentId): VerifySpec => ({ kind: 'part-installed', target });

const step = (id: string, textAr: string, hintAr: string, verify: VerifySpec): MissionStep => ({
  id,
  textAr,
  hintAr,
  verify,
});

