/**
 * postEngine.ts — محرك نتيجة POST (الاختبار الذاتي عند التشغيل).
 *
 * منطق حتمي بالترتيب: عطل مزود الطاقة (F12) ← حالة مزود الطاقة المباشرة (غياب/تلف) ←
 * لا طاقة ← اللوحة الأم (غياب/تلف) ← قطع تغذية/معالج ← ذاكرة (غائبة أو غير متوافقة)
 * ← مبرد ← عرض ← تهوية ← تخزين ← إقلاع سليم.
 * كل نتيجة محاكاة تعليمية (isSimulated: true) وتتضمن SIM_NOTE_AR لتمييز أن
 * الأجهزة الحقيقية قد تختلف عن المنصة المرجعية (LGA1700/DDR5/ATX).
 */

import { isInstalled } from '../types';
import type { DiagnosisFinding, SimulationState } from '../types';

export const SIM_NOTE_AR =
  'نتيجة POST هنا محاكاة تعليمية لمنصة مرجعية (LGA1700/DDR5/ATX)؛ سلوك الأجهزة الحقيقية يختلف حسب التصميم.';

/** يشغّل محاكاة POST على الحالة الحالية ويعيد نتيجة تشخيص واحدة. */
export function runPost(s: SimulationState): DiagnosisFinding {
  const { flags, parts, peripherals } = s;

  // 0) مزود طاقة معطل — الضغط على الزر لا ينتج عنه شيء (سيناريو تعليمي F12).
  if (peripherals.psuDead) {
    return {
      code: 'POWER_OFF',
      titleAr: 'لا استجابة للتشغيل — اشتباه مزود الطاقة',
      detailsAr: [
        'كابل الكهرباء موصول والزر مضغوط، لكن لا مراوح تدور ولا أضواء ولا صفارة — استجابة ميتة تمامًا.',
        'الشك يتجه إلى مزود الطاقة نفسه أو مسار التيار أمامه، وليس إلى القطع الداخلية.',
        'الدليل الحاسم تعليميًا: مراوح لا تتحرك إطلاقًا مع كهرباء موصولة وغطاء مغلق.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'تأكد أن كابل الكهرباء من الحائط إلى PSU سليم ومقفول في مكانه.',
        'في جهاز حقيقي: جرّب كابلًا آخر وافحص مفتاح 115/230V خلف PSU — ولم تفتح PSU أبدًا (خطر قاتل).',
        'المحاكاة تسمح باستبدال مزود الطاقة معيبٍ بأخر من المخزن التعليمي.',
        SIM_NOTE_AR,
      ],
      isSimulated: true,
    };
  }

  // 0.5) حالة مزود الطاقة المباشرة (إصلاح S1) — مسار عطل F12 أعلاه لم يُمسّ:
  // machineFlags تسمح بالضغط على زر التشغيل مع PSU غائبة، فالحكم هنا في مستوى POST —
  // (التالف يُفحص في الفرع التالي حتى لا يبتلع هذا الفرع رسالته الخاصة).
  if (parts.psu !== 'damaged' && !isInstalled(parts.psu)) {
    const statusWord =
      parts.psu === 'removed' ? 'مُزالة' : parts.psu === 'awaiting' ? 'ناقصة' : 'نصف مفكوكة';
    return {
      code: 'POWER_OFF',
      titleAr: 'لا استجابة للتشغيل — وحدة الإمداد غير مثبتة',
      detailsAr: [
        'وحدة الإمداد غير مثبتة — لا يمكن تشغيل الجهاز',
        `حالة مزود الطاقة الحالية: ${statusWord} — بدون مزود طاقة لا يمر أي جهد إلى اللوحة: لا مراوح ولا أضواء ولا أي علامة حياة.`,
        'اختبار POST لا يبدأ أصلًا قبل وجود مزود طاقة مثبت ومغذٍّ للوحة.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ الجهاز وافصل الكهرباء، ثم أعد تركيب مزود الطاقة في مكانه واربط براغيه.',
        'أعد توصيل كابلاته (ATX 24-pin وEPS وكابل طاقة البطاقة) ثم شغّل وأعد الفحص.',
      ],
      isSimulated: true,
    };
  }

  // 0.6) مزود طاقة تالف بتلف مباشر (إصلاح S1 — وضع الاستكشاف) — ليس عطل F12 أعلاه
  // (فلو كان psuDead لكان مسار F12 قد أعاد نتيجته قبل هذا السطر).
  if (parts.psu === 'damaged') {
    return {
      code: 'POWER_OFF',
      titleAr: 'لا استجابة للتشغيل — وحدة الإمداد تالفة',
      detailsAr: [
        'وحدة الإمداد تالفة (محاكاة عطل F12 هي الحالة التدريبية المقصودة — هذا تلف مباشر).',
        'مزود تالف يُستبدل كاملًا ولا يُفتح أبدًا — مكثفاته تحمل شحنة قاتلة حتى بعد الفصل.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ الجهاز وافصل الكهرباء، ثم استبدل مزود الطاقة التالف بآخر سليم من المخزن التعليمي.',
        'بعد الاستبدال أعد توصيل كابلاته ثم شغّل وأعد الفحص.',
      ],
      isSimulated: true,
    };
  }

  // 1) لا طاقة — لا يبدأ أي فحص أصلًا.
  if (!flags.powerOn || !flags.acConnected) {
    return {
      code: 'POWER_OFF',
      titleAr: 'لا طاقة — لا يبدأ أي فحص',
      detailsAr: [
        'الجهاز مطفأ أو كابل الكهرباء غير موصول — لا مراوح تدور ولا أضواء.',
        'اختبار POST لا يبدأ إطلاقًا قبل توفر الطاقة.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'وصّل كابل الكهرباء من الحائط إلى مزود الطاقة.',
        'تأكد أن الغطاء مغلق، ثم شغّل من زر الطاقة وأعد الفحص.',
      ],
      isSimulated: true,
    };
  }

  // 1.5) اللوحة الأم غائبة أو تالفة (إصلاح S1) — فشل POST مباشر يُنهي الفحص هنا:
  // كل القطع تُركَّب عليها وتُختبَر عبرها، فغيابها/تلفها يُفشل POST قبل أي فحص آخر.
  if (!isInstalled(parts.motherboard)) {
    const statusWord =
      parts.motherboard === 'removed'
        ? 'مُزالة'
        : parts.motherboard === 'awaiting'
          ? 'ناقصة'
          : parts.motherboard === 'damaged'
            ? 'تالفة'
            : 'نصف مفكوكة';
    return {
      code: 'POST_FAIL',
      titleAr: 'فشل POST — اللوحة الأم غير مثبتة أو تالفة',
      detailsAr: [
        'اللوحة الأم غير مثبتة/تالفة — لا يمكن إتمام اختبار POST.',
        `حالة اللوحة الحالية: ${statusWord} — المعالج والذاكرة والتغذية كلها تجلس عليها، فلا فحص بلا لوحة حاضرة سالمة.`,
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ وافصل الكهرباء، ثم أعد تركيب اللوحة الأم على حواملها واربط مساميرها.',
        'أعد توصيل ATX 24-pin وEPS وموصلات اللوحة الأمامية بعد التثبيت، ثم أعد الفحص.',
      ],
      isSimulated: true,
    };
  }

  // 2) قطع التغذية/المعالج الحرجة — فشل POST مباشر.
  if (!isInstalled(parts.cpu) || !isInstalled(parts.atx24) || !isInstalled(parts.eps)) {
    const causes: string[] = [];
    if (!isInstalled(parts.cpu)) {
      causes.push('لا يوجد POST: المعالج غير مثبت — بدونه لا ينفّذ الجهاز أي أمر إقلاع.');
    }
    if (!isInstalled(parts.atx24)) {
      causes.push('لا يوجد POST: كابل ATX 24-pin غير موصل — اللوحة الأم بلا تغذية رئيسية.');
    }
    if (!isInstalled(parts.eps)) {
      causes.push('لا يوجد POST: كابل EPS 8-pin غير موصل — المعالج بلا تغذية.');
    }
    return {
      code: 'POST_FAIL',
      titleAr: 'فشل POST — قطع حرجة ناقصة',
      detailsAr: [
        ...causes,
        'نمط بيب تعليمي (نصيًا): لا بيب إطلاقًا أو بيب طويل متكرر مع بقاء المراوح تدور — أنماط البيب تختلف بين شركات BIOS/UEFI فلا تُحكم بالنمط وحده.',
        'قد تدور المراوح وتبدو المؤشرات حيةً مع غياب أي صورة — يُخلط كثيرًا بينه وبين عطل الشاشة.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ الجهاز وافصل الكهرباء قبل أي تدخل.',
        'أعد تركيب القطع الناقصة أعلاه بالترتيب: المعالج برافعة مفتوحة ومثلث محاذاة، ثم ATX 24-pin حتى طقّة القفل، ثم EPS 8-pin في الزاوية العلوية.',
        'أعد التشغيل وأعد الفحص بعد كل تعديل واحد فقط.',
      ],
      isSimulated: true,
    };
  }

  // 3) الذاكرة غائبة أو غير متوافقة — فشل POST مع نمط بيب تعليمي.
  if (!isInstalled(parts.ram) || peripherals.ramIncompatible) {
    const causes: string[] = [];
    if (!isInstalled(parts.ram)) {
      causes.push('لا يوجد POST: الذاكرة غير مثبتة — لا يمكن تنفيذ الاختبار الذاتي بلا ذاكرة.');
    }
    if (peripherals.ramIncompatible) {
      causes.push('لا يوجد POST: الذاكرة المركّبة غير متوافقة مع اللوحة (نوع/سرعة خارج نطاق الدعم) — المقبسان لكل طرف يعني وحدة غير مطابقة تُرفض في الاختبار الذاتي.');
    }
    return {
      code: 'POST_FAIL',
      titleAr: 'فشل POST — مشكلة في الذاكرة',
      detailsAr: [
        ...causes,
        'نمط بيب تعليمي (نصيًا): بيبات متكررة قصيرة (خمس بيبات عند عدم التوافق) — لكن أنماط البيب تختلف بين المنصات وشركات BIOS/UEFI.',
        'الذاكرة شرط أساسي لنجاح POST نفسه — لا يصل النظام لمرحلة الصورة أبدًا بدونها.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ وافصل الكهرباء وافتح الغطاء.',
        'أعد تركيب الوحدة بمحاذاة سن الفتحة (Keying) واضغط حتى طقّة المزالج على الطرفين.',
        'إن تكرر الفشل: جرّب وحدة أخرى معروفة سلامتها، وتحقق من قائمة التوافق (QVL) للوحة.',
        'أعد التشغيل وأعد الفحص.',
      ],
      isSimulated: true,
    };
  }

  // 4) المبرد ناقص — POST ناجح مع تحذير حراري/حماية.
  if (!isInstalled(parts.cooler)) {
    return {
      code: 'POST_PASS_BOOT_WARNING',
      titleAr: 'POST ناجح مع تحذير — مبرد المعالج مفقود',
      detailsAr: [
        'POST نجح: المعالج والذاكرة والتغذية الأساسية تعمل.',
        'تحذير حراري: المبرد غير مثبت — بعض اللوحات تعرض CPU Fan Error أو تمنع التشغيل عبر الحماية الحرارية، وأخرى تسمح بالتشغيل ثوانٍ معدودة ثم تنطفئ.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ الجهاز فورًا — لا يُشغَّل معالج بلا تبريد حتى في المحاكاة.',
        'ركّب المبرد بمعجون حراري مناسب ووصّل مروحته بمنفذ CPU_FAN ثم أعد الفحص.',
      ],
      isSimulated: true,
    };
  }

  // 5) بطاقة الرسوميات ناقصة — لا إشارة عرض (المعالج المرجعي بلا رسوميات مدمجة).
  if (!isInstalled(parts.gpu)) {
    return {
      code: 'POST_PASS_BOOT_WARNING',
      titleAr: 'POST ناجح مع تحذير — لا إشارة عرض',
      detailsAr: [
        'لا توجد بطاقة رسوميات والمعالج المرجعي بلا رسوميات مدمجة — لا إشارة عرض على الشاشة.',
        'الجهاز قد يكون يعمل فعلًا (مراوح وأضواء) دون أي صورة — لا تفترض فورًا أنه معطل.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ وركّب بطاقة رسوميات، أو على منصات أخرى اختر معالجًا برسوميات مدمجة.',
        'تأكد من كابل الشاشة ومن اختيار مصدر الإدخال الصحيح على الشاشة.',
      ],
      isSimulated: true,
    };
  }

  // 6) البطاقة مثبتة لكن بلا كابل طاقة.
  if (!isInstalled(parts.gpuPower)) {
    return {
      code: 'POST_PASS_BOOT_WARNING',
      titleAr: 'POST ناجح مع تحذير — بطاقة بلا كابل طاقة',
      detailsAr: [
        'البطاقة بلا كابل طاقة: قد تفشل تحت الحمل حسب نموذجها — بعض البطاقات الاقتصادية تكفيها طاقة الفتحة، والأقوى تنطفئ عند أول حمل.',
        'قد يصل الجهاز إلى سطح المكتب ثم ينطفئ عند تشغيل ألعاب أو اختبارات ضغط.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ ووصّل كابل طاقة البطاقة مباشرة من مزود الطاقة.',
        'تجنّب المحوّلات الملتوية كمصدر تغذية دائم.',
      ],
      isSimulated: true,
    };
  }

  // 7) التهوية ناقصة — POST ناجح مع تحذير تهوية.
  if (!isInstalled(parts.fans)) {
    return {
      code: 'POST_PASS_BOOT_WARNING',
      titleAr: 'POST ناجح مع تحذير — تهوية الهيكل ناقصة',
      detailsAr: [
        'مراوح الهيكل غير مثبتة: POST ناجح والإقلاع ممكن، لكن درجات الحرارة ستتراكم مع كل دقيقة عمل.',
        'منافذ SYS_FAN فارغة قد تُظهر تنبيه Fan Error في بعض اللوحات، والهواء الساكن داخل الهيكل يرفع حرارة البطاقة ومراحل التغذية تدريجيًا.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ وركّب مراوح الهيكل باتجاه تدفق صحيح: دخول من الأمام وخروج من الخلف.',
        'وصّل موصلات المراوح برؤوس SYS_FAN/CPU_FAN على اللوحة.',
      ],
      isSimulated: true,
    };
  }

  // 8) التخزين ناقص أو غير موصول — POST ≠ إقلاع (القرص الميكانيكي بديل إقلاع صالح).
  const hasM2 = isInstalled(parts.ssd);
  const hasHdd = isInstalled(parts.hdd) && isInstalled(parts.sataData) && isInstalled(parts.sataPower);
  if (!hasM2 && !hasHdd) {
    const causes: string[] = [];
    if (!isInstalled(parts.ssd) && !isInstalled(parts.hdd)) {
      causes.push('لا يوجد جهاز تخزين مثبت أصلًا — لا M.2 ولا قرص ميكانيكي.');
    } else if (!isInstalled(parts.ssd) && !hasHdd) {
      causes.push('قرص M.2 غائب، والقرص الميكانيكي موجود لكن كابلاته غير مكتملة (بيانات/طاقة) — لا جهاز إقلاع صالح.');
    } else {
      causes.push('قرص M.2 غائب — القرص الميكانيكي موجود وكابلاته سليمة لكنه بلا نظام تشغيل.');
    }
    return {
      code: 'POST_PASS_BOOT_WARNING',
      titleAr: 'POST ناجح مع تحذير — لا جهاز إقلاع',
      detailsAr: [
        ...causes,
        'POST ناجح لكن لا يوجد جهاز إقلاع — انتبه: POST منفصل عن الإقلاع.',
        'تدخل المحاكاة إعدادات UEFI تلقائيًا وتعرض قائمة أجهزة الإقلاع الفارغة.',
        SIM_NOTE_AR,
      ],
      nextStepsAr: [
        'أطفئ وركّب قرص M.2، أو ثبّت القرص الميكانيكي وكابليه (بيانات من اللوحة وطاقة من PSU).',
        'راجع ترتيب الإقلاع (Boot Order) في إعدادات UEFI.',
      ],
      isSimulated: true,
    };
  }

  // 9) التجميعة مكتملة — POST ناجح وإقلاع سليم.
  return {
    code: 'POST_PASS_BOOT_OK',
    titleAr: 'POST ناجح والإقلاع سليم',
    detailsAr: [
      'اختبار POST ناجح: التغذية والمعالج والذاكرة والعرض والتخزين مكتملة في المحاكاة.',
      'الإقلاع إلى نظام التشغيل متوقع بلا تحذيرات.',
      SIM_NOTE_AR,
    ],
    nextStepsAr: [
      'أكمل الجلسة بمهمة جديدة أو اختبر سيناريوهات SMART التعليمية.',
      'على جهاز حقيقي: راقب الحرارة وحدّث BIOS/UEFI عند الحاجة فقط.',
    ],
    isSimulated: true,
  };
}
